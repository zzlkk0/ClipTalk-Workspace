'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {startFixture,macauDate}=require('./fixture');
const {chromium}=require(process.env.CLIPTALK_TEST_TOOLS ? path.join(process.env.CLIPTALK_TEST_TOOLS,'playwright') : 'playwright');

async function waitText(page,selector,text){await page.waitForFunction(({selector,text})=>document.querySelector(selector)?.textContent.includes(text),{selector,text});}
async function login(browser,f,username,viewport={width:1440,height:900}) {
  const context=await browser.newContext({viewport,locale:'zh-CN'});
  const page=await context.newPage();
  await page.goto(f.base+'/login.html');
  await page.locator('#username').fill(username);await page.locator('#password').fill(f.password);
  await page.locator('#btn').click();await page.waitForURL(f.base+'/');
  await waitText(page,'#status-text','已连接');
  page.on('dialog',dialog=>dialog.accept());
  return {context,page};
}

test('browser: remove role toggle, device sync, named archives, clear, quota editing and mobile layout',async t=>{
  const f=await startFixture(t);
  const browser=await chromium.launch({executablePath:process.env.CLIPTALK_CHROME || undefined,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  t.after(()=>browser.close());
  const errors=[];
  const a=await login(browser,f,'alice'),a2=await login(browser,f,'alice'),b=await login(browser,f,'bob'),admin=await login(browser,f,'test_admin');
  for(const p of [a.page,a2.page,b.page,admin.page])p.on('pageerror',error=>errors.push(error.message));
  assert.equal(await a.page.locator('#role-tag').count(),0);
  await waitText(a.page,'#storage-usage','1.00 GB');
  await a.page.locator('#clipboard-area').fill('我的多设备剪贴板');
  await a2.page.waitForFunction(()=>document.querySelector('#clipboard-area').value==='我的多设备剪贴板');
  assert.equal(await b.page.locator('#clipboard-area').inputValue(),'');
  await a.page.locator('#chat-input').fill('测试多设备对话');await a.page.locator('#chat-input').press('Enter');
  await waitText(a2.page,'#chat-messages','测试多设备对话');
  assert.equal(await b.page.locator('#chat-messages').textContent(),'');
  const filename='报告"中文.txt';
  const uploadResponse=a.page.waitForResponse(response=>response.url()===f.base+'/upload');
  await a.page.locator('#file-input').setInputFiles({name:filename,mimeType:'text/plain',buffer:Buffer.from('归档文件内容')});
  const uploaded=await uploadResponse; assert.equal(uploaded.status(),200);
  const displayedName=(await uploaded.json()).files[0].originalName;
  assert.ok(displayedName.includes('报告'));assert.ok(displayedName.includes('中文'));
  await waitText(a.page,'#file-list',displayedName);await waitText(a2.page,'#file-list',displayedName);
  assert.equal(await b.page.locator('#file-list .file-item').count(),0);
  await a.page.locator('#panel-chat button[data-t="workspace.archive"]').click();
  const archiveTitle='<img src=x onerror=window.__injected=1> 研究档案';
  await a.page.locator('#archive-title').fill(archiveTitle);
  await a.page.locator('#archive-start').fill(macauDate());await a.page.locator('#archive-end').fill(macauDate());
  await a.page.locator('#archive-scope').selectOption('both');await a.page.locator('#archive-submit').click();
  await a.page.waitForFunction(()=>document.querySelector('#archives-dialog').open);
  await waitText(a.page,'#archive-list',archiveTitle);
  await a2.page.waitForFunction(()=>document.querySelector('#chat-messages').children.length===0&&document.querySelector('#file-list .file-item')===null);
  assert.equal(await a.page.evaluate(()=>window.__injected),undefined);
  await a.page.locator('#archive-list .archive-card button').click();
  await waitText(a.page,'#archive-detail-title',archiveTitle);
  await waitText(a.page,'#archive-messages','测试多设备对话');await waitText(a.page,'#archive-files',displayedName);
  assert.equal(await a.page.locator('#archive-detail-title img').count(),0);
  await a.page.locator('#archive-rename-title').fill('第一阶段归档');
  await a.page.locator('#archive-rename-form button[data-t="workspace.rename"]').click();
  await waitText(a.page,'#archive-detail-title','第一阶段归档');
  await a.page.locator('#archive-rename-form button[data-t="workspace.restore"]').click();
  await a.page.waitForFunction(()=>!document.querySelector('#archive-detail-dialog').open);
  await waitText(a2.page,'#chat-messages','测试多设备对话');await waitText(a2.page,'#file-list',displayedName);
  await a.page.locator('#archives-dialog .dialog-header button').click();
  await a.page.locator('#panel-chat button[data-t="workspace.clear_all"]').click();
  await a2.page.waitForFunction(()=>document.querySelector('#chat-messages').children.length===0);
  await a.page.locator('#panel-files button[data-t="workspace.clear_all"]').click();
  await a2.page.waitForFunction(()=>document.querySelector('#file-list .file-item')===null);
  await a.page.locator('#lang-btn').click();await waitText(a.page,'.workspace-note','Each account');
  await a.page.locator('button[data-t="workspace.archives"]').click();
  await waitText(a.page,'#archive-list','No archives yet');
  await a.page.locator('#archives-dialog .dialog-header button').click();
  await a.page.locator('#lang-btn').click();
  await admin.page.locator('#admin-btn').click();await waitText(admin.page,'#storage-table','alice');
  const row=admin.page.locator('tr[data-storage-user="alice"]');
  await row.locator('input').fill('1');await row.locator('button').click();await waitText(admin.page,'#quota-msg-alice','已保存');
  await waitText(a.page,'#storage-usage','1.00 MB');await waitText(a2.page,'#storage-usage','1.00 MB');
  await a.page.locator('#file-input').setInputFiles({name:'over-limit.bin',mimeType:'application/octet-stream',buffer:Buffer.alloc(1048576)});
  await waitText(a.page,'#notice','空间不足');assert.equal(await a.page.locator('#file-list .file-item').count(),0);
  const mobile=await login(browser,f,'bob',{width:390,height:844});
  mobile.page.on('pageerror',error=>errors.push(error.message));
  assert.equal(await mobile.page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await mobile.page.locator('button[data-t="workspace.archives"]').click();
  await waitText(mobile.page,'#archive-list','还没有归档');
  const artifacts=path.join(__dirname,'..','validation','screenshots');fs.mkdirSync(artifacts,{recursive:true});
  await mobile.page.screenshot({path:path.join(artifacts,'mobile-archives.png'),fullPage:true});
  await a.page.screenshot({path:path.join(artifacts,'desktop-workspace.png'),fullPage:true});
  await admin.page.screenshot({path:path.join(artifacts,'admin-storage.png'),fullPage:true});
  assert.deepEqual(errors,[]);
});
