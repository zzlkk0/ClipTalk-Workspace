'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { startFixture, json } = require('./fixture');
const { chromium } = require(process.env.CLIPTALK_TEST_TOOLS ? path.join(process.env.CLIPTALK_TEST_TOOLS, 'playwright') : 'playwright');
const waitText = (page, selector, text) => page.waitForFunction(({ selector, text }) => document.querySelector(selector)?.textContent.includes(text), { selector, text });

test('browser agent access: defaults, one-time key display, XSS-safe names, logs, revoke, themes and mobile', async t => {
  const f = await startFixture(t, { legacy: false });
  const browser = await chromium.launch({ executablePath: process.env.CLIPTALK_CHROME || undefined, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  t.after(() => browser.close()); const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
  const errors = []; page.on('pageerror', error => errors.push(error.message)); page.on('dialog', dialog => dialog.accept());
  await page.goto(f.base + '/login.html'); await page.locator('#username').fill('alice'); await page.locator('#password').fill(f.password); await page.locator('#btn').click(); await page.waitForURL(f.base + '/');
  await page.goto(f.base + '/account.html'); await page.locator('#agent-access-link').click();
  await waitText(page, '#key-list', '还没有创建密钥');
  assert.equal(await page.locator('#key-scopes input:checked').count(), 2);
  const name = '<img src=x onerror=window.injected=1> Test';
  await page.locator('#key-label').fill(name); await page.locator('[value="clipboard:write"]').check();
  await page.locator('#key-password').fill(f.password); await page.locator('#key-form button').click();
  await page.locator('#created-key').waitFor({ state: 'visible' }); const token = await page.locator('#new-token').inputValue(); assert.match(token, /^ct_/);
  assert.equal(await page.locator('#key-password').inputValue(), '');
  await waitText(page, '#key-list', name); assert.equal(await page.locator('#key-list img').count(), 0);
  assert.equal(await page.evaluate(() => window.injected), undefined);
  assert.equal((await f.request('/api/v1/clipboard', null, { ...json('PUT', { text: 'private browser test content' }), headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + token } })).status, 200);
  await page.locator('#audit-refresh').click(); await waitText(page, '#audit-list', '修改剪贴板');
  assert.equal(await page.locator('[data-action="PUT /clipboard"]').count(), 1);
  assert.equal((await page.locator('#audit-list').textContent()).includes('private browser test content'), false);
  await page.locator('#hide-token').click(); assert.equal(await page.locator('#new-token').inputValue(), '');
  await page.reload(); await waitText(page, '#key-list', name); assert.equal(await page.locator('#created-key').isHidden(), true);
  assert.equal((await page.content()).includes(token), false);
  await page.locator('#key-list button').click(); await waitText(page, '#key-list', '已撤销');
  assert.equal((await f.request('/api/v1/me', null, { headers: { Authorization: 'Bearer ' + token } })).status, 401);
  await page.locator('[data-theme-toggle]').click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const screenshots = path.join(__dirname, '../validation/screenshots'); fs.mkdirSync(screenshots, { recursive: true });
  await page.screenshot({ path: path.join(screenshots, 'agent-access-mobile.png'), fullPage: true });
  await page.locator('#language-button').click(); await waitText(page, 'h1', 'Agent access');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: path.join(screenshots, 'agent-access-desktop.png'), fullPage: true });
  assert.deepEqual(errors, []);
});
